import java.io.BufferedReader;
import java.io.BufferedWriter;
import java.net.URL;
import java.time.Duration;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.concurrent.Callable;
import java.util.concurrent.ForkJoinPool;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;

/**
 * The members added on 11.10.2026 outside java.time, on the real library.
 *
 * Process gained the character half of its three streams and waitFor(Duration); TimeUnit gained
 * the java.time bridge that waitFor(Duration) rests on; ClassLoader gained seven of its twelve;
 * ForkJoinPool gained one of twelve. Each class's own source says what was left out and why — and
 * ClassLoader's says it at length, because the first draft of that block added one field to a
 * class the virtual machine reads by offset, and every binary built from it aborted before main.
 *
 * WHERE THE EXPECTED VALUES COME FROM. JDK 25, asked directly. TimeUnit.convert(Duration) is the
 * reason that matters here rather than being a formality: it is the one body in this commit that
 * could not be copied — OpenJDK 25's TimeUnit carries scale, secRatio and maxSecs as fields and
 * this one does not — so it was rewritten against this class's own convert(long, TimeUnit), and
 * the rewriting is all in the saturation and the negative carry. The sixteen durations below
 * include both sides of the long-nanoseconds edge: 9223372036s + 854775807ns is exactly
 * Long.MAX_VALUE nanoseconds, and one nanosecond more must saturate rather than wrap.
 */
public class LoaderProcessCheck {

    static int checked, failed;

    static void eq(String what, Object got, Object want) {
        checked++;
        if (!String.valueOf(got).equals(String.valueOf(want))) {
            failed++;
            System.out.println("  MISMATCH " + what + ": got " + got + ", wanted " + want);
        }
    }

    // ---- TimeUnit.convert(Duration) ---------------------------------------------------------
    //
    // Each row: the duration, then the answer per unit in TimeUnit.values() order —
    // NANOSECONDS, MICROSECONDS, MILLISECONDS, SECONDS, MINUTES, HOURS, DAYS. Generated by
    // running the same expressions on JDK 25.
    static final long[][] EXPECTED = {
        {0L, 0L, 0L, 0L, 0L, 0L, 0L},
        {1L, 0L, 0L, 0L, 0L, 0L, 0L},
        {999999999L, 999999L, 999L, 0L, 0L, 0L, 0L},
        {1500000000L, 1500000L, 1500L, 1L, 0L, 0L, 0L},
        {1500000000L, 1500000L, 1500L, 1L, 0L, 0L, 0L},
        {-500000000L, -500000L, -500L, 0L, 0L, 0L, 0L},
        {-1L, 0L, 0L, 0L, 0L, 0L, 0L},
        {-1000000000L, -1000000L, -1000L, -1L, 0L, 0L, 0L},
        {-999999999L, -999999L, -999L, 0L, 0L, 0L, 0L},
        {86400000000000L, 86400000000L, 86400000L, 86400L, 1440L, 24L, 1L},
        {-86400000000000L, -86400000000L, -86400000L, -86400L, -1440L, -24L, -1L},
        {Long.MAX_VALUE, Long.MAX_VALUE, Long.MAX_VALUE, Long.MAX_VALUE,
         153722867280912930L, 2562047788015215L, 106751991167300L},
        {Long.MIN_VALUE, Long.MIN_VALUE, Long.MIN_VALUE, Long.MIN_VALUE,
         -153722867280912930L, -2562047788015215L, -106751991167300L},
        {9223372036854775807L, 9223372036854775L, 9223372036854L, 9223372036L,
         153722867L, 2562047L, 106751L},
        {9223372036854775807L, 9223372036854775L, 9223372036854L, 9223372036L,
         153722867L, 2562047L, 106751L},
        {-9223372035854775808L, -9223372035854775L, -9223372035854L, -9223372035L,
         -153722867L, -2562047L, -106751L},
    };

    static Duration[] durations() {
        return new Duration[] {
            Duration.ZERO,
            Duration.ofNanos(1),
            Duration.ofNanos(999999999L),
            Duration.ofMillis(1500),
            Duration.ofSeconds(1, 500000000),
            Duration.ofSeconds(-1, 500000000),
            Duration.ofNanos(-1),
            Duration.ofSeconds(-1),
            Duration.ofSeconds(-1, 1),
            Duration.ofDays(1),
            Duration.ofDays(-1),
            Duration.ofSeconds(Long.MAX_VALUE, 999999999),
            Duration.ofSeconds(Long.MIN_VALUE),
            Duration.ofSeconds(9223372036L, 854775807),
            Duration.ofSeconds(9223372036L, 854775808L),
            Duration.ofSeconds(-9223372036L, 145224192),
        };
    }

    static void theTimeUnitBridge() {
        Duration[] ds = durations();
        TimeUnit[] us = TimeUnit.values();
        eq("TimeUnit has seven units", us.length, 7);
        for (int i = 0; i < ds.length; i++) {
            for (int j = 0; j < us.length; j++) {
                eq("convert(" + ds[i] + ") to " + us[j], us[j].convert(ds[i]), EXPECTED[i][j]);
            }
        }

        // The round trip the specification states: convert(Duration.of(n, unit.toChronoUnit()))
        // gives n back.
        for (int j = 0; j < us.length; j++) {
            eq("round trip through " + us[j],
                    us[j].convert(Duration.of(7, us[j].toChronoUnit())), 7L);
            eq("of(toChronoUnit()) is the identity", TimeUnit.of(us[j].toChronoUnit()), us[j]);
        }

        checked++;
        try {
            TimeUnit.of(ChronoUnit.WEEKS);
            failed++;
            System.out.println("  MISMATCH TimeUnit.of(WEEKS): accepted, wanted"
                    + " IllegalArgumentException");
        } catch (IllegalArgumentException expected) {
            // what JDK 25 does — there is no TimeUnit for a week
        }
    }

    // ---- Process ----------------------------------------------------------------------------
    static void theProcessReaders() {
        Process p;
        try {
            p = new ProcessBuilder("/bin/echo", "hello").start();
        } catch (Exception e) {
            // A target where a child process cannot be started says so and declines, rather than
            // failing: on iOS this is not a defect but the platform, and the readers are still
            // compiled and still part of the library.
            System.out.println("  no child process on this target (" + e + ") — Process declined");
            return;
        }
        try {
            BufferedReader out = p.inputReader();
            eq("inputReader reads the child's output", out.readLine(), "hello");
            eq("inputReader is the same reader twice", p.inputReader() == out, true);

            checked++;
            try {
                p.inputReader(java.nio.charset.Charset.forName("UTF-16"));
                failed++;
                System.out.println("  MISMATCH inputReader with a second charset: accepted,"
                        + " wanted IllegalStateException");
            } catch (IllegalStateException expected) {
                // The specified behaviour: one charset per process, and saying so beats handing
                // back a reader that decodes with something the caller did not ask for.
            }

            eq("errorReader is a reader", p.errorReader() != null, true);
            eq("errorReader is the same reader twice", p.errorReader() == p.errorReader(), true);

            // waitFor(Duration) on a process that has already finished, and on one that has not.
            eq("waitFor(Duration) sees the exit", p.waitFor(Duration.ofSeconds(10)), true);
            eq("the child exited cleanly", p.exitValue(), 0);
        } catch (Exception e) {
            failed++;
            System.out.println("  MISMATCH Process: " + e);
        }

        try {
            Process slow = new ProcessBuilder("/bin/sleep", "5").start();
            eq("waitFor(Duration) gives up when the time is up",
                    slow.waitFor(Duration.ofMillis(50)), false);
            BufferedWriter in = slow.outputWriter();
            eq("outputWriter is the same writer twice", slow.outputWriter() == in, true);
            slow.destroyForcibly();
        } catch (Exception e) {
            failed++;
            System.out.println("  MISMATCH Process timeout: " + e);
        }
    }

    // ---- ClassLoader -----------------------------------------------------------------------
    static class Named extends ClassLoader {
        Named(ClassLoader parent) {
            super(parent);
        }

        /** getClassLoadingLock is protected, so a subclass is the only way to ask it. */
        Object lockFor(String className) {
            return getClassLoadingLock(className);
        }
    }

    static void theClassLoader() throws Exception {
        ClassLoader system = ClassLoader.getSystemClassLoader();

        // getName() and the named constructor are deliberately absent — see the comment at the
        // top of ClassLoader's added block, where the abort they caused is measured. What is
        // asserted here is that their absence is the only consequence: the ordinary constructor
        // still works and still refuses a null parent, which is this class's own older rule.
        ClassLoader made = new Named(system);
        eq("a loader keeps its parent", made.getParent() == system, true);

        checked++;
        try {
            new Named(null);
            failed++;
            System.out.println("  MISMATCH a null parent: accepted, and this runtime's loadClass"
                    + " would then throw NullPointerException on first use");
        } catch (NullPointerException expected) {
            // the answer ClassLoader(ClassLoader) has always given here
        }

        // The platform loader has the shape the specification describes: a real loader whose own
        // parent is the boot loader, i.e. null.
        ClassLoader platform = ClassLoader.getPlatformClassLoader();
        eq("there is a platform loader", platform != null, true);
        eq("its parent is the boot loader", platform.getParent(), "null");
        eq("it loads a platform class", platform.loadClass("java.lang.String"),
                "class java.lang.String");

        eq("no loader here is parallel capable", system.isRegisteredAsParallelCapable(), false);
        // For a loader that is not parallel capable the lock is the loader itself, which is what
        // the specification says and what this runtime's class loading actually does.
        Named probe = new Named(system);
        eq("the class loading lock is the loader", probe.lockFor("x") == probe, true);
        checked++;
        try {
            probe.lockFor(null);
            failed++;
            System.out.println("  MISMATCH getClassLoadingLock(null): accepted, wanted"
                    + " NullPointerException");
        } catch (NullPointerException expected) {
            // what JDK 25 does for a loader that is not parallel capable
        }

        eq("getDefinedPackages answers an array", system.getDefinedPackages() != null, true);
        checked++;
        try {
            system.getDefinedPackage(null);
            failed++;
            System.out.println("  MISMATCH getDefinedPackage(null): accepted, wanted"
                    + " NullPointerException");
        } catch (NullPointerException expected) {
            // what JDK 25 does
        }

        // resources(String) is the stream form of getResources, and it has to find the same
        // things. A resource every build of this library carries is the one to ask for.
        List<URL> fromStream = new ArrayList<URL>();
        java.util.Iterator<URL> it = system.resources("java/lang/String.class").iterator();
        while (it.hasNext()) {
            fromStream.add(it.next());
        }
        int fromEnumeration = 0;
        java.util.Enumeration<URL> e = system.getResources("java/lang/String.class");
        while (e.hasMoreElements()) {
            e.nextElement();
            fromEnumeration++;
        }
        eq("resources() finds what getResources() finds", fromStream.size(), fromEnumeration);
        // Reported rather than asserted, because the number is a fact about the image and not
        // about the method: an ahead-of-time binary has no class path to walk, so both answers are
        // normally zero here and the assertion above is then only saying that the two agree about
        // nothing. On a host JVM the same code finds the class. Printing it keeps that visible
        // instead of letting a trivially-true comparison look like coverage.
        System.out.println("  resources(\"java/lang/String.class\") found " + fromStream.size()
                + " on this image, getResources() " + fromEnumeration);

        checked++;
        try {
            system.resources(null);
            failed++;
            System.out.println("  MISMATCH resources(null): accepted, wanted NullPointerException");
        } catch (NullPointerException expected) {
            // what JDK 25 does
        }
    }

    // ---- ForkJoinPool ----------------------------------------------------------------------
    static void theUninterruptibleInvokeAll() {
        Collection<Callable<String>> tasks = new ArrayList<Callable<String>>();
        for (int i = 0; i < 4; i++) {
            final int n = i;
            tasks.add(new Callable<String>() {
                @Override
                public String call() {
                    return "task" + n;
                }
            });
        }
        ForkJoinPool pool = new ForkJoinPool(2);
        try {
            // Interrupted on purpose before the call: the method's whole promise is that it
            // finishes anyway, and an interrupt that is merely never noticed would pass a weaker
            // test than this one.
            Thread.currentThread().interrupt();
            List<Future<String>> futures = pool.invokeAllUninterruptibly(tasks);
            eq("every task is answered", futures.size(), 4);

            // THE INTERRUPT IS READ BEFORE THE RESULTS, and the order is the point rather than
            // tidiness. The first draft of this read the results first and three assertions went
            // red: ForkJoinTask.get() tests the interrupt flag before it looks at the task, so it
            // threw InterruptedException on a task that had completed long before — which is
            // precisely the evidence that invokeAllUninterruptibly did what it promises and left
            // the flag standing. Thread.interrupted() both asserts and clears it, so what follows
            // is an ordinary read.
            eq("the interrupt is still pending afterwards", Thread.interrupted(), true);

            StringBuilder got = new StringBuilder();
            for (int i = 0; i < futures.size(); i++) {
                eq("task " + i + " completed", futures.get(i).isDone(), true);
                try {
                    got.append(futures.get(i).get()).append(' ');
                } catch (Exception ex) {
                    failed++;
                    System.out.println("  MISMATCH task " + i + ": " + ex);
                }
            }
            // In the order they were asked for, which is what the specification says and what a
            // caller reading results positionally depends on.
            eq("the results keep the order of the tasks", got.toString().trim(),
                    "task0 task1 task2 task3");
        } finally {
            pool.shutdown();
        }
    }

    public static void main(String[] args) throws Exception {
        theTimeUnitBridge();
        theProcessReaders();
        theClassLoader();
        theUninterruptibleInvokeAll();
        System.out.println(checked + " checked, " + failed + " failed");
        if (failed > 0) {
            System.exit(1);
        }
    }
}
